// Наряды-награды за достижения (awards.ts): бантик, платок, ошейник с колокольчиком, шапочка, корона.
// Надевает их тот же `dress` из sprite.ts, что и праздничные шапку с тыквой, — от ряда макушки
// головы анфас, поэтому наряд сидит в любой позе, где голова смотрит на человека.
// Ключи палитры — цифры: буквы заняты кошкой, вещами и праздниками.

/** Наряд за достижение. */
export type Wear = 'bow' | 'bandana' | 'bell' | 'beanie' | 'crown';

/** В порядке, в каком их обычно получают: так и показываем в гардеробе. */
export const WEARS: readonly Wear[] = ['bow', 'bandana', 'bell', 'beanie', 'crown'];

/** Деталь наряда. Ширина — как у головы, 12; столбец 0 — левый край головы. */
export interface Piece {
  rows: string[];
  /** Верхний ряд детали относительно ряда макушки: −4 — над головой, 7 — подбородок. */
  dy: number;
  /**
   * Под мордой: рисуется только поверх самой кошки. Миска, передний бортик лежака или лотка
   * закрывают ошейник, как закрывают подбородок, а в пустоте под головой он не висит.
   */
  under?: boolean;
}

